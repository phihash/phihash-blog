export type ChecklistItem = {
  id: string;
  /** 確認する項目。「〜できているか」の問いかけ形で書く */
  label: string;
  /** なぜ・どう確認するかの補足（任意） */
  hint?: string;
};

export type Example = {
  /** 実例の説明。自分のアプリでどう適用したか等 */
  caption: string;
  /** public/ 配下のスクショパス（任意・後で追加）。例: "/examples/color-1.png" */
  image?: string;
};

/**
 * 概要を構成するブロック。
 * - 文字列        … 段落
 * - { heading }   … 小見出し
 * - { term, text }… 対比・定義（用語＋説明）
 * 単純な文字列だけでも書けるし、必要なところだけ構造化できる。
 */
export type OverviewBlock =
  | string
  | { heading: string }
  | { term: string; text: string };

export type Topic = {
  id: string;
  title: string;
  /** 概要（段落・小見出し・対比ブロックの並び） */
  overview: OverviewBlock[];
  /** 実例（スクショは後入れ可・無くてもよい） */
  examples?: Example[];
  /** チェックリスト項目（概要だけの読み物トピックでは省略可） */
  checklist?: ChecklistItem[];
};

